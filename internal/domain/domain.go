// Package domain contains the provider-independent models used by music-syncer.
//
// Every music service (Yandex Music, Spotify, ...) is adapted to the Provider
// interface, so the synchronization engine never talks to an API directly.
package domain

import (
	"context"
	"errors"
	"fmt"
	"strings"
	"time"
)

// Name identifies a music provider.
type Name string

const (
	Yandex  Name = "yandex"
	Spotify Name = "spotify"
)

// ParseName validates a provider name.
func ParseName(s string) (Name, error) {
	switch Name(strings.ToLower(strings.TrimSpace(s))) {
	case Yandex:
		return Yandex, nil
	case Spotify:
		return Spotify, nil
	default:
		return "", fmt.Errorf("unknown provider %q (expected %q or %q)", s, Yandex, Spotify)
	}
}

// DisplayName returns a human-friendly provider name.
func (n Name) DisplayName() string {
	switch n {
	case Yandex:
		return "Yandex Music"
	case Spotify:
		return "Spotify"
	default:
		return string(n)
	}
}

// Capabilities describes what a provider can do. It lets the CLI and the sync
// engine give an honest answer instead of failing halfway through.
type Capabilities struct {
	Playlists      bool
	LikedTracks    bool
	FollowedArtist bool
	HistoryRead    bool
	// HistoryWrite is false for every public music API: listening history is
	// generated by the player, not by the user. Providers may still expose
	// history as a playlist import.
	HistoryWrite bool
}

// Account is the authenticated user of a provider.
type Account struct {
	Provider    Name   `json:"provider"`
	ID          string `json:"id"`
	Login       string `json:"login,omitempty"`
	DisplayName string `json:"display_name,omitempty"`
	Email       string `json:"email,omitempty"`
}

// Track is a provider-independent track representation.
//
// ID and AlbumID are native identifiers of the provider that returned the
// track. AlbumID is required by Yandex Music when inserting a track into a
// playlist.
type Track struct {
	Provider   Name     `json:"provider"`
	ID         string   `json:"id"`
	AlbumID    string   `json:"album_id,omitempty"`
	Title      string   `json:"title"`
	Artists    []string `json:"artists,omitempty"`
	Album      string   `json:"album,omitempty"`
	DurationMS int      `json:"duration_ms,omitempty"`
	ISRC       string   `json:"isrc,omitempty"`
	Explicit   bool     `json:"explicit,omitempty"`
	URL        string   `json:"url,omitempty"`
}

// ArtistLine joins the track artists with a comma.
func (t Track) ArtistLine() string { return strings.Join(t.Artists, ", ") }

// PrimaryArtist returns the first artist, or an empty string.
func (t Track) PrimaryArtist() string {
	if len(t.Artists) == 0 {
		return ""
	}
	return t.Artists[0]
}

// Key returns a stable provider-scoped identifier.
func (t Track) Key() string { return string(t.Provider) + ":track:" + t.ID }

// String returns a human-readable description, useful in logs and reports.
func (t Track) String() string {
	switch {
	case t.Title == "":
		return t.Key()
	case t.ArtistLine() == "":
		return t.Title
	default:
		return t.Title + " — " + t.ArtistLine()
	}
}

// Artist is a provider-independent artist representation.
type Artist struct {
	Provider Name   `json:"provider"`
	ID       string `json:"id"`
	Name     string `json:"name"`
	URL      string `json:"url,omitempty"`
}

// Key returns a stable provider-scoped identifier.
func (a Artist) Key() string { return string(a.Provider) + ":artist:" + a.ID }

// Playlist is playlist metadata. Tracks are loaded lazily because playlists
// can be large and most synchronization steps only need the metadata.
type Playlist struct {
	Provider    Name   `json:"provider"`
	ID          string `json:"id"`
	Kind        string `json:"kind,omitempty"`
	OwnerID     string `json:"owner_id,omitempty"`
	Name        string `json:"name"`
	Description string `json:"description,omitempty"`
	TrackCount  int    `json:"track_count"`
	URL         string `json:"url,omitempty"`

	// Generated is true for algorithmic playlists (Yandex "Плейлист дня",
	// Spotify editorial mixes, ...). They are skipped by default.
	Generated bool `json:"generated,omitempty"`
	// Special marks service-owned collections such as Yandex "Мне нравится"
	// (liked tracks). They have their own synchronization category.
	Special string `json:"special,omitempty"`
	// ReadOnly is true when the current user cannot read the playlist's tracks
	// or modify it (for example, a followed Spotify playlist).
	ReadOnly bool `json:"read_only,omitempty"`
}

// Key returns a stable provider-scoped identifier.
func (p Playlist) Key() string { return string(p.Provider) + ":playlist:" + p.ID }

// String returns a human-readable description.
func (p Playlist) String() string { return p.Name }

// PlayEvent is a single listening event.
type PlayEvent struct {
	Track    Track     `json:"track"`
	PlayedAt time.Time `json:"played_at"`
	Context  string    `json:"context,omitempty"`
}

// Provider is the contract implemented by every music service adapter.
type Provider interface {
	Name() Name
	Capabilities() Capabilities
	Account(ctx context.Context) (Account, error)

	// Playlists returns playlists visible to the current user. For Yandex
	// Music this includes owned and algorithmic playlists.
	Playlists(ctx context.Context) ([]Playlist, error)
	// PlaylistTracks returns the playlist contents in order.
	PlaylistTracks(ctx context.Context, playlist Playlist) ([]Track, error)

	LikedTracks(ctx context.Context, limit int) ([]Track, error)
	LikedArtists(ctx context.Context, limit int) ([]Artist, error)
	History(ctx context.Context, since time.Time, limit int) ([]PlayEvent, error)

	// SearchTracks looks up candidates for a track. The provider must return
	// full track metadata (including its own ID and album ID) because the
	// result is written back to that provider.
	SearchTracks(ctx context.Context, track Track, limit int) ([]Track, error)
	SearchArtists(ctx context.Context, artist Artist, limit int) ([]Artist, error)

	CreatePlaylist(ctx context.Context, name, description string) (Playlist, error)
	AddTracks(ctx context.Context, playlist Playlist, tracks []Track) error
	RemoveTracks(ctx context.Context, playlist Playlist, tracks []Track) error

	LikeTracks(ctx context.Context, tracks []Track) error
	FollowArtists(ctx context.Context, artists []Artist) error
}

// APIError is returned by provider clients for non-2xx HTTP responses.
type APIError struct {
	Provider   Name
	StatusCode int
	Message    string
	Err        error
}

func (e *APIError) Error() string {
	msg := strings.TrimSpace(e.Message)
	if msg == "" && e.Err != nil {
		msg = e.Err.Error()
	}
	if msg == "" {
		msg = "request failed"
	}
	return fmt.Sprintf("%s: HTTP %d: %s", e.Provider.DisplayName(), e.StatusCode, msg)
}

func (e *APIError) Unwrap() error { return e.Err }

// IsUnauthorized reports whether an error is an authentication failure.
func IsUnauthorized(err error) bool {
	var apiErr *APIError
	return errors.As(err, &apiErr) && apiErr.StatusCode == 401
}

// IsNotFound reports whether an error is a 404.
func IsNotFound(err error) bool {
	var apiErr *APIError
	return errors.As(err, &apiErr) && apiErr.StatusCode == 404
}

// ErrNotSupported is returned when a provider cannot perform an operation.
var ErrNotSupported = errors.New("operation is not supported by this provider")
